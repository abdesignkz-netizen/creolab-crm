export function analyticsText(source: string, params: Record<string, string | number> = {}, locale = getPublicLocale()) {
  const translated = locale === "kk" ? analyticsKk[source] : undefined;
  return translated ? translated.replace(/\{(\w+)\}/g, (match, key) => String(params[key] ?? match)) : uiText(source, params, locale);
}

export function planExplanation(plan: any, text = analyticsText) {
  if (!plan) return "";
  if (plan.status === "filtered") return text("Общий план компании не сравнивается с отфильтрованной частью продаж. Снимите фильтры.");
  if (plan.status === "unbounded") return text("Для плана выберите период с началом и концом.");
  if (plan.status === "legacy") return text("Прежний план не привязан к месяцу. Задайте месячные планы в правилах работы со сделками.");
  if (plan.status === "missing") return text("План не задан на месяцы: {months} ({currency}).", { months: plan.missingMonths?.join(", ") || "—", currency: plan.currency });
  return [text(plan.prorated ? "План рассчитан по доле календарных дней каждого месяца." : "План за полные выбранные месяцы."),
    plan.missingAmounts ? text("Процент не рассчитан: есть продажи без суммы.") : plan.exact === "0" ? text("Процент не рассчитан: план равен нулю.") : ""].filter(Boolean).join(" ");
}
