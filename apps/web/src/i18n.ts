export function normalizeLocale(value?: string | null): Locale {
  if (value === "kk" || value === "en" || value === "ru") return value;
  return "ru";
}

// Keep profile normalization deterministic. Only public pages infer a language.
export function getPublicLocale(): Locale {
  try {
    const saved = localStorage.getItem("basqar.locale");
    if (saved === "ru" || saved === "kk" || saved === "en") return saved;
  } catch { /* Storage may be unavailable in private browsing. */ }
  if (typeof navigator !== "undefined" && /^kk(?:-|$)/i.test(navigator.language)) return "kk";
  return "ru";
}

export function rememberLocale(locale: Locale) {
  try { localStorage.setItem("basqar.locale", locale); } catch { /* Optional preference. */ }
}

export function t(locale: Locale, key: string, values: Record<string, string | number> = {}) {
  const text = dict[locale][key] || dict.ru[key] || key;
  return text.replace(/\{([a-zA-Z]\w*)\}/g, (placeholder, name) =>
    Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : placeholder);
}

export function applyDocumentLocale(locale: Locale) {
  document.documentElement.lang = locale === "kk" ? "kk" : locale;
}

/** Translate known authentication errors without applying translation to user content. */
export function authErrorMessage(locale: Locale, err: unknown, fallbackKey = "login.genericError") {
  const error = err as { message?: string; code?: string } | null;
  if (error?.message === "Failed to fetch" || error?.message === "HTTP 500") return t(locale, "login.requestNetwork");
  // Some API codes cover several actions; keep their different recovery instructions.
  const messages: Record<string, string> = {
    "Код недействителен. Начните регистрацию заново.": "login.restartRegistration",
    "Слишком много повторных отправок. Начните регистрацию заново.": "login.resendLimit",
    "Слишком много попыток. Запросите новый код.": "login.tooManyCodes",
    "Пароли не совпадают": "login.passwordMismatch",
    "Минимум 8 символов": "login.passwordMin8",
    "Минимум 10 символов": "login.passwordMin10",
  };
  const codes: Record<string, string> = {
    legal_consent_required: "legal.required", legal_revision_changed: "legal.changed",
    invalid_credentials: "login.invalidCredentials", account_disabled: "login.accountDisabled",
    forbidden: "login.adminOnly", account_exists: "login.accountExists", consumed: "login.alreadyVerified",
    rate_limited: "login.rateLimited", expired_code: "login.resetExpired", too_many_attempts: "login.resetTooMany",
    invalid_code: "login.resetInvalidCode", invalid_token: "login.resetInvalidToken", validation_error: "login.invalidFields",
  };
  const key = messages[error?.message || ""] || codes[error?.code || ""];
  if (key) return t(locale, key);
  // Preserve existing server detail in Russian. Untranslated server text must not leak
  // into Kazakh forms; known errors above retain their specific recovery instructions.
  if (locale !== "kk" && error?.message && !/^HTTP \d+/.test(error.message)) return error.message;
  return t(locale, fallbackKey);
}

export function accountErrorMessage(locale: Locale, message?: string) {
  const keys = [
    "settings.incorrectPassword", "settings.passwordTooShort", "settings.noEditPermission",
    "settings.invalidImageType", "settings.invalidImage", "settings.emptyImage", "settings.largeImage",
    "settings.fileReadError", "login.passwordMismatch",
  ];
  const key = keys.find(key => dict.ru[key] === message || dict[locale][key] === message);
  if (key) return t(locale, key);
  return locale === "kk" || !message ? t(locale, "settings.saveFailed") : message;
}
